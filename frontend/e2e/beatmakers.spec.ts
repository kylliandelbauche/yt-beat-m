import { expect, test } from '@playwright/test'
import { mkdtemp, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'

test('corriger un beatmaker, mémoriser sa chaîne, réimporter et actualiser sans couper la lecture', async ({ page }, testInfo) => {
  test.setTimeout(60000)
  const original = (await (await page.request.get('/api/library')).json()).library
  const root = await mkdtemp(path.join(tmpdir(), 'beatmaker-browser-'))
  const token = (await (await page.request.get('/api/session')).json()).token
  const headers = { Origin: 'http://127.0.0.1:8767', 'X-Session-Token': token }
  try {
    const selected = await page.request.post('/api/library', { headers, data: { path: root, create: true, name: 'Identité des beatmakers' } })
    expect(selected.ok()).toBe(true)
    await page.goto('/')
    const input = page.getByRole('textbox', { name: 'Lien YouTube de la prod' })
    await input.fill('https://youtu.be/CREATOR0001')
    await page.getByRole('button', { name: 'Importer la prod', exact: true }).click()
    const first = page.getByRole('button', { name: 'Écouter Prod beatmaker 1', exact: true })
    await expect(first).toBeVisible({ timeout: 15000 })
    await first.click()
    const audio = page.locator('audio')
    await expect(audio).toHaveJSProperty('paused', false)
    await page.getByRole('button', { name: 'Détails de Prod beatmaker 1', exact: true }).click()
    let dialog = page.getByRole('dialog')
    await expect(dialog.locator('dl').getByText('Raw', { exact: true })).toBeVisible()
    await dialog.getByText('Annotations et origine', { exact: true }).click()
    await expect(dialog.getByText('Crédit explicite du titre ou de la description.', { exact: true })).toBeVisible()
    await dialog.getByRole('button', { name: 'Modifier la prod', exact: true }).click()
    await dialog.getByRole('textbox', { name: 'Nom du beatmaker', exact: true }).fill('Studio Nova')
    await dialog.getByRole('checkbox', { name: 'Mémoriser pour les prochains imports de cette chaîne', exact: true }).check()
    await dialog.getByRole('button', { name: 'Enregistrer les modifications', exact: true }).click()
    await expect(dialog.getByRole('status')).toHaveText('Informations enregistrées.')
    await expect(dialog.locator('dl').getByText('Studio Nova', { exact: true })).toBeVisible()
    await expect(audio).toHaveJSProperty('paused', false)
    await page.keyboard.press('Escape')
    await page.reload()
    await page.getByRole('button', { name: 'Détails de Prod beatmaker 1', exact: true }).click()
    dialog = page.getByRole('dialog')
    await expect(dialog.locator('dl').getByText('Studio Nova', { exact: true })).toBeVisible()
    await dialog.getByText('Annotations et origine', { exact: true }).click()
    await expect(dialog.getByText('Nom mémorisé pour cette chaîne : Studio Nova', { exact: true })).toBeVisible()
    await page.keyboard.press('Escape')
    await input.fill('https://youtu.be/CREATOR0002')
    await page.getByRole('button', { name: 'Importer la prod', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Écouter Prod beatmaker 2', exact: true })).toBeVisible({ timeout: 15000 })
    await page.getByRole('searchbox', { name: 'Rechercher une prod' }).fill('studio nova')
    await expect(first).toBeVisible()
    await expect(page.getByRole('button', { name: 'Écouter Prod beatmaker 2', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Détails de Prod beatmaker 2', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByText('Annotations et origine', { exact: true }).click()
    await expect(dialog.getByText('Nom mémorisé pour cette chaîne.', { exact: true })).toBeVisible()
    await dialog.getByRole('button', { name: 'Modifier la prod', exact: true }).click()
    await dialog.getByRole('checkbox', { name: 'Supprimer la règle de chaîne', exact: true }).check()
    await dialog.getByRole('button', { name: 'Enregistrer les modifications', exact: true }).click()
    await expect(dialog.getByRole('checkbox', { name: 'Supprimer la règle de chaîne', exact: true })).toHaveCount(0)
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: 'Effacer les filtres', exact: true }).click()
    await page.getByRole('button', { name: 'Actualiser', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: 'beatmaker(s) actualisé(s)' })).toBeVisible()
    await page.getByRole('button', { name: 'Détails de Prod beatmaker 2', exact: true }).click()
    dialog = page.getByRole('dialog')
    await expect(dialog.locator('dl').getByText('Raw', { exact: true })).toBeVisible()
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: 'Détails de Prod beatmaker 1', exact: true }).click()
    dialog = page.getByRole('dialog')
    await expect(dialog.locator('dl').getByText('Studio Nova', { exact: true })).toBeVisible()
    await dialog.getByRole('button', { name: 'Modifier la prod', exact: true }).click()
    await dialog.getByRole('button', { name: 'Enregistrer les modifications', exact: true }).scrollIntoViewIfNeeded()
    await page.screenshot({ path: testInfo.outputPath('beatmaker-editor.png') })
    await dialog.getByRole('checkbox', { name: 'Revenir à la proposition', exact: true }).check()
    await dialog.getByRole('button', { name: 'Enregistrer les modifications', exact: true }).click()
    await expect(dialog.locator('dl').getByText('Raw', { exact: true })).toBeVisible()
  } catch (cause) {
    const jobs = await page.request.get('/api/imports')
    console.error('État des imports de la bibliothèque de test :', await jobs.text())
    throw cause
  } finally {
    const restored = await page.request.post('/api/library', { headers, data: { path: original.root } })
    expect(restored.ok()).toBe(true)
    await rm(root, { recursive: true, force: true })
  }
})
