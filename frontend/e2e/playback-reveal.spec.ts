import { expect, test } from '@playwright/test'

for (const viewport of [{ width: 1440, height: 900 }, { width: 390, height: 650 }]) {
  test(`Play/Pause partagé, fichier et géométrie stable sur ${viewport.width}`, async ({ page }, testInfo) => {
    await page.setViewportSize(viewport)
    let requests = 0
    let release: () => void = () => {}
    await page.route('**/api/beats/*/reveal', async (route) => {
      expect(route.request().method()).toBe('POST')
      expect(route.request().url()).toMatch(/\/api\/beats\/00000000-0000-0000-0000-000000000001\/reveal$/)
      requests += 1
      await new Promise<void>((resolve) => { release = resolve })
      await route.fulfill(requests === 1 ? { status: 404, json: { detail: 'Fichier introuvable ; vérifier le disque.' } } : { json: { revealed: true } })
    })
    await page.goto('/')
    const audio = page.locator('audio')
    const first = page.locator('.beat-card').filter({ has: page.getByRole('button', { name: 'Détails de R&B Mélancolique', exact: true }) })
    for (const layout of ['Grandes pochettes', 'Cartes horizontales']) {
      await page.getByRole('button', { name: layout, exact: true }).click()
      const before = await first.boundingBox()
      await first.getByRole('button', { name: 'Écouter R&B Mélancolique', exact: true }).focus()
      await page.keyboard.press('Enter')
      await expect(audio).toHaveJSProperty('paused', false)
      await expect(first.getByRole('button', { name: 'Mettre en pause R&B Mélancolique', exact: true })).toBeVisible()
      const during = await first.boundingBox()
      expect(during?.width).toBe(before?.width); expect(during?.height).toBe(before?.height)
      await first.getByRole('button', { name: 'Mettre en pause R&B Mélancolique', exact: true }).click()
      await expect(audio).toHaveJSProperty('paused', true)
      await audio.evaluate((el: HTMLAudioElement) => { el.currentTime = 7; el.dataset.identity = 'same-player' })
    }
    await first.getByRole('button', { name: 'Détails de R&B Mélancolique', exact: true }).click()
    const dialog = page.getByRole('dialog')
    const detailPlay = dialog.locator('.detail-play')
    const geometry = () => dialog.locator('.detail-cover, .detail-music, .detail-links, .detail-right, .modal-actions').evaluateAll((elements) => elements.map((el) => { const r = el.getBoundingClientRect(); return [r.x, r.y, r.width, r.height] }))
    await expect(detailPlay).toBeVisible()
    const before = await geometry()
    await detailPlay.click()
    await expect(audio).toHaveJSProperty('paused', false)
    await expect(detailPlay).toHaveAccessibleName('Mettre en pause R&B Mélancolique')
    expect(await audio.evaluate((el: HTMLAudioElement) => el.currentTime)).toBeGreaterThanOrEqual(7)
    await expect(audio).toHaveAttribute('data-identity', 'same-player')
    await audio.evaluate((el: HTMLAudioElement) => { el.pause(); el.currentTime = 9 })
    await expect(detailPlay).toHaveAccessibleName('Écouter R&B Mélancolique')
    await audio.evaluate((el: HTMLAudioElement) => el.play())
    await expect(detailPlay).toHaveAccessibleName('Mettre en pause R&B Mélancolique')
    await detailPlay.click()
    await audio.evaluate((el: HTMLAudioElement) => { el.currentTime = 9 })
    const reveal = dialog.getByRole('button', { name: 'Afficher le fichier ↗', exact: true })
    const sale = dialog.locator('.sale-link, .sale-link-empty')
    expect((await reveal.boundingBox())!.y).toBeLessThan((await sale.boundingBox())!.y)
    for (const attempt of [1, 2]) {
      await reveal.click()
      await expect.poll(() => requests).toBe(attempt)
      await expect(reveal).toBeDisabled()
      expect(await geometry()).toEqual(before)
      release()
      await expect(reveal).toBeEnabled()
      if (attempt === 1) await expect(dialog.getByRole('alert')).toContainText('vérifier le disque')
      else await expect(dialog.getByRole('alert')).toHaveCount(0)
      expect(await geometry()).toEqual(before)
      await expect(audio).toHaveJSProperty('paused', true)
      await expect(audio).toHaveJSProperty('currentTime', 9)
    }
    await page.screenshot({ path: testInfo.outputPath('playback-reveal.png') })
    await page.keyboard.press('Escape')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await first.getByRole('button', { name: 'Écouter R&B Mélancolique', exact: true }).click()
    await page.getByRole('searchbox', { name: 'Rechercher une prod' }).fill('Drill')
    await expect(first).toHaveCount(0)
    await expect(audio).toHaveAttribute('data-identity', 'same-player')
    await expect(audio).toHaveJSProperty('paused', false)
    await page.getByRole('button', { name: 'Écouter Drill minuit', exact: true }).click()
    await expect(audio).toHaveCount(1)
    await expect(audio).toHaveJSProperty('paused', false)
    await expect(audio).not.toHaveAttribute('data-identity', 'same-player')
    await expect(page.getByRole('button', { name: /^Mettre en pause/ })).toHaveCount(1)
    // play() can clear paused before the new track's metadata has arrived.
    await expect.poll(() => audio.evaluate((el: HTMLAudioElement) => Number.isFinite(el.duration) && el.duration > 0.1 && el.readyState >= HTMLMediaElement.HAVE_METADATA)).toBe(true)
    await audio.evaluate((el: HTMLAudioElement) => { el.currentTime = el.duration - 0.1 })
    await expect(audio).toHaveJSProperty('ended', true)
    await expect(page.getByRole('button', { name: 'Écouter Drill minuit', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Écouter Drill minuit', exact: true }).click()
    await expect(audio).toHaveJSProperty('paused', false)
    expect(await audio.evaluate((el: HTMLAudioElement) => el.currentTime)).toBeLessThan(5)
    await audio.evaluate((el: HTMLAudioElement) => { el.pause(); el.dispatchEvent(new Event('error')) })
    await expect(page.getByRole('button', { name: /^Mettre en pause/ })).toHaveCount(0)
    await expect(page.getByRole('alert')).toContainText('Fichier audio indisponible')
  })

  test(`espace compact et réservé sous l’import sur ${viewport.width}`, async ({ page }) => {
    await page.setViewportSize(viewport)
    let active = false
    await page.route('**/api/imports', (route) => {
      if (route.request().method() === 'POST') active = true
      const job = { id: 'layout-progress', source_url: 'https://youtu.be/PROGRESS001', state: 'running', stage: 'downloading', progress: 32, beat_id: null }
      return route.fulfill({ json: route.request().method() === 'POST' ? { job, beat_id: null, duplicate: false } : { jobs: active ? [job] : [] } })
    })
    await page.goto('/')
    const panel = page.getByRole('region', { name: 'Importer une prod' })
    const before = await panel.boundingBox()
    const slot = page.locator('.import-progress-list')
    expect((await slot.boundingBox())!.height).toBe(20)
    expect(await panel.evaluate((el) => getComputedStyle(el).marginBottom)).toBe('16px')
    await page.getByRole('textbox', { name: 'Lien YouTube de la prod' }).fill('https://youtu.be/PROGRESS001')
    await page.getByRole('button', { name: 'Importer la prod', exact: true }).click()
    await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow', '32')
    expect(await panel.boundingBox()).toEqual(before)
    expect((await slot.boundingBox())!.height).toBe(20)
  })
}
