test('une grande grille réserve sa hauteur et son défilement pendant une déconnexion', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  let offline = false
  await page.route('**/api/health', (route) => offline ? route.abort() : route.continue())
  await page.route('**/api/beats?*', async (route) => {
    const result = await (await route.fetch()).json()
    await route.fulfill({ json: { beats: Array.from({ length: 7 }, (_, n) => ({ ...result.beats[0], id: `synthetic-${n}` })), total: 7 } })
  })
  await page.goto('/')
  await expect(page.locator('.beat-card')).toHaveCount(7)
  await expect.poll(() => page.locator('.catalog-stage').evaluate((el) => parseFloat(getComputedStyle(el).minHeight))).toBeGreaterThan(2000)
  await page.evaluate(() => window.scrollTo(0, 1000))
  const before = await page.locator('.collection-toolbar').evaluate((el) => el.getBoundingClientRect().top + scrollY)
  offline = true
  await expect(page.getByRole('heading', { name: 'Le moteur local ne répond pas', exact: true })).toBeVisible({ timeout: 10000 })
  expect(await page.locator('.collection-toolbar').evaluate((el) => el.getBoundingClientRect().top + scrollY)).toBe(before)
  expect(await page.evaluate(() => scrollY)).toBe(1000)
})

test('filtres : sélections immédiates, effacement local, focus distinct et erreur BPM stable', async ({ page }, testInfo) => {
  await page.route('**/api/catalog/filters', (route) => route.fulfill({ json: { keys: Array.from({ length: 30 }, (_, n) => `Note ${n}`), makers: ['Nova', 'Ryo'], channels: [], styles: [], moods: [] } }))
  await page.goto('/')
  const tone = page.locator('.filter-menu').filter({ has: page.locator('summary', { hasText: 'Tonalité' }) })
  await tone.locator('summary').click()
  const check = tone.getByRole('checkbox', { name: 'Note 0', exact: true })
  await check.focus()
  await expect(check).not.toBeChecked()
  await check.check()
  await tone.getByRole('checkbox', { name: 'Non renseigné', exact: true }).check()
  await expect(tone).toHaveAttribute('open')
  await expect(tone.locator('.filter-count')).toHaveText('2')
  expect(await tone.locator('.filter-choices').evaluate((el) => el.scrollHeight > el.clientHeight)).toBe(true)
  await tone.getByRole('button', { name: 'Tout effacer', exact: true }).click()
  await expect(check).not.toBeChecked()
  await expect(tone).toHaveAttribute('open')
  await page.keyboard.press('Escape')
  await expect(tone.locator('summary')).toBeFocused()
  await tone.locator('summary').click()
  await page.locator('.section-heading h2').click()
  await expect(tone.locator('summary')).toBeFocused()
  const bpm = page.locator('.filter-menu').filter({ has: page.locator('summary', { hasText: 'BPM' }) })
  await bpm.locator('summary').click()
  const apply = bpm.getByRole('button', { name: 'Appliquer les BPM', exact: true })
  const before = await apply.boundingBox()
  await bpm.getByLabel('BPM minimum').fill('150')
  await bpm.getByLabel('BPM maximum').fill('100')
  await apply.click()
  await expect(bpm.getByRole('alert')).toContainText('minimum')
  await expect(bpm.getByLabel('BPM minimum')).toHaveAttribute('aria-invalid', 'true')
  expect(await apply.boundingBox()).toEqual(before)
  await bpm.getByRole('button', { name: 'Tout effacer', exact: true }).click()
  await expect(bpm.getByLabel('BPM minimum')).toHaveValue('')
  await expect(bpm.getByRole('alert')).toBeEmpty()
  await page.keyboard.press('Escape')
  const sort = page.getByRole('combobox', { name: 'Trier les prods', exact: true })
  await expect(sort.locator('option')).toHaveCount(4)
  await sort.selectOption('published_asc')
  await expect(sort.locator('option:checked')).toHaveCount(1)
  await page.screenshot({ path: testInfo.outputPath('filters.png') })
})
