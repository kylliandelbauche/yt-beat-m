import { expect, test } from '@playwright/test'

test('catalogue vide puis erreur récupérable au chargement', async ({ page }) => {
  await page.route('**/api/beats?*', (route) => route.fulfill({ json: { beats: [], total: 0 } }))
  await page.goto('/')
  await expect(page.getByText('Une place pour tes premières prods.', { exact: true })).toBeVisible()
  await page.unroute('**/api/beats?*')
  await page.route('**/api/beats?*', (route) => route.fulfill({ status: 503, json: { detail: 'Catalogue temporairement indisponible.' } }))
  await page.reload()
  await expect(page.getByRole('alert')).toContainText('Catalogue temporairement indisponible.')
  await page.unroute('**/api/beats?*')
  await page.getByRole('button', { name: 'Réessayer', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Écouter R&B Mélancolique', exact: true })).toBeVisible()
})

test('fiche accessible au clavier et description traitée comme du texte', async ({ page }) => {
  await page.goto('/')
  const details = page.getByRole('button', { name: 'Détails de R&B Mélancolique', exact: true })
  await details.focus()
  await details.press('Enter')
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('heading', { name: 'R&B Mélancolique', exact: true })).toBeVisible()
  await expect(dialog.getByText('F# minor', { exact: true })).toBeVisible()
  await expect(dialog.getByText('<script>window.untrusted = true</script> Description de test.', { exact: true })).toBeVisible()
  await expect(dialog.locator('script')).toHaveCount(0)
  await expect(dialog.getByRole('link', { name: 'Licence de test ↗' })).toHaveAttribute('href', 'https://example.org/license')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(details).toBeFocused()
})

test('lecteur unique conservé pendant la recherche et l’ouverture de fiche', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Écouter R&B Mélancolique', exact: true }).click()
  const audio = page.locator('audio')
  await expect(audio).toHaveJSProperty('paused', false)
  await audio.evaluate((element: HTMLAudioElement) => { element.currentTime = 5 })
  await expect.poll(() => audio.evaluate((element: HTMLAudioElement) => element.currentTime)).toBeGreaterThanOrEqual(5)
  const source = await audio.getAttribute('src')
  await page.getByRole('searchbox', { name: 'Rechercher une prod' }).fill('drill')
  await expect(page.getByRole('button', { name: 'Écouter R&B Mélancolique', exact: true })).toHaveCount(0)
  await expect(audio).toHaveAttribute('src', source!)
  await expect(audio).toHaveJSProperty('paused', false)
  await page.getByRole('button', { name: 'Détails de Drill minuit', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(audio).toHaveJSProperty('paused', false)
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Écouter Drill minuit', exact: true }).click()
  await expect(page.locator('audio')).toHaveCount(1)
  await expect(page.locator('audio')).not.toHaveAttribute('src', source!)
  await expect(page.locator('audio')).toHaveJSProperty('paused', false)
})

