import { expect, test } from '@playwright/test'
import { mkdtemp, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'

test('éditer les informations, filtrer et retirer les filtres sans redémarrer la piste', async ({ page }, testInfo) => {
  test.setTimeout(60000)
  const original = (await (await page.request.get('/api/library')).json()).library
  const root = await mkdtemp(path.join(tmpdir(), 'metadata-browser-'))
  const token = (await (await page.request.get('/api/session')).json()).token
  const headers = { Origin: 'http://127.0.0.1:8767', 'X-Session-Token': token }
  try {
    expect((await page.request.post('/api/library', { headers, data: { path: root, create: true, name: 'Annotations musicales' } })).ok()).toBe(true)
    for (const id of ['CREATOR0001', 'CREATOR0002']) {
      expect((await page.request.post('/api/imports', { headers, data: { url: `https://youtu.be/${id}` } })).ok()).toBe(true)
    }
    await page.goto('/')
    const first = page.locator('.beat-card').getByRole('button', { name: 'Écouter Prod beatmaker 1', exact: true })
    await expect(first).toBeVisible({ timeout: 15000 })
    await expect(page.locator('.beat-card').getByRole('button', { name: 'Écouter Prod beatmaker 2', exact: true })).toBeVisible({ timeout: 15000 })
    const seeded = (await (await page.request.get('/api/beats')).json()).beats.find((beat: { title: string }) => beat.title === 'Prod beatmaker 1')
    expect((await page.request.patch(`/api/beats/${seeded.id}/metadata`, { headers, data: { styles: ['Hoodtrap'], moods: ['Mélancolique', 'love'] } })).ok()).toBe(true)
    await page.reload()
    await first.click()
    const audio = page.locator('audio')
    await expect(audio).toHaveJSProperty('paused', false)
    await audio.evaluate((node: HTMLAudioElement) => { node.pause(); node.currentTime = 10 })
    const src = await audio.getAttribute('src')
    await page.getByRole('button', { name: 'Détails de Prod beatmaker 1', exact: true }).click()
    let dialog = page.getByRole('dialog')
    await dialog.getByRole('button', { name: 'Modifier la prod', exact: true }).click()
    await dialog.getByLabel('BPM', { exact: true }).fill('150')
    await dialog.getByLabel('Tonalité', { exact: true }).fill('pas une note')
    await dialog.getByRole('button', { name: 'Enregistrer les modifications', exact: true }).click()
    await expect(dialog.getByRole('alert')).toContainText('Tonalité :')
    await dialog.getByLabel('Tonalité', { exact: true }).fill('F mineur')
    await dialog.getByLabel('Page de vente', { exact: true }).fill('https://example.org/produit/la-vie-est-belle/')
    await page.screenshot({ path: testInfo.outputPath('clean-editor.png') })
    await dialog.getByRole('button', { name: 'Enregistrer les modifications', exact: true }).click()
    await expect(dialog.getByRole('status')).toContainText('Informations enregistrées.')
    await expect(dialog.getByLabel('BPM', { exact: true })).toHaveValue('150')
    await expect(dialog.getByLabel('Tonalité', { exact: true })).toHaveValue('F minor')
    await expect(dialog.getByRole('link', { name: 'Page de vente ↗' })).toHaveAttribute('href', 'https://example.org/produit/la-vie-est-belle/')
    await expect(audio).toHaveJSProperty('paused', true)
    await expect(audio).toHaveJSProperty('currentTime', 10)
    await expect(audio).toHaveAttribute('src', src!)
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await page.getByRole('searchbox', { name: 'Rechercher une prod', exact: true }).fill('melancolique')
    await expect(first).toBeVisible()
    await expect(page.locator('.beat-card')).toHaveCount(1)
    const menu = (label: string) => page.locator('.filter-menu').filter({ has: page.locator('summary', { hasText: label }) })
    await menu('BPM').locator('summary').click()
    await page.getByLabel('BPM minimum').fill('160')
    await page.getByLabel('BPM maximum').fill('145')
    await page.getByRole('button', { name: 'Appliquer les BPM' }).click()
    await expect(menu('BPM').getByRole('alert')).toContainText('minimum')
    await page.getByLabel('BPM minimum').fill('145')
    await page.getByLabel('BPM maximum').fill('155')
    await page.getByRole('button', { name: 'Appliquer les BPM' }).click()
    await menu('Tonalité').locator('summary').click()
    await menu('Tonalité').getByRole('checkbox', { name: 'F minor', exact: true }).check()
    await menu('Beatmaker').locator('summary').click()
    await menu('Beatmaker').getByRole('checkbox', { name: 'Raw', exact: true }).check()
    await menu('Style').locator('summary').click()
    await menu('Style').getByRole('checkbox', { name: 'Hoodtrap', exact: true }).check()
    await page.keyboard.press('Escape')
    await expect(page.locator('.beat-card')).toHaveCount(1)
    await expect(first).toBeVisible()
    await expect(audio).toHaveJSProperty('paused', true)
    await expect(audio).toHaveJSProperty('currentTime', 10)
    await page.getByRole('button', { name: 'Tonalité : F minor ×', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Tonalité : F minor ×', exact: true })).toHaveCount(0)
    await page.getByRole('combobox', { name: 'Trier les prods' }).selectOption('published_desc')
    await expect(page.getByRole('status').filter({ hasText: 'publications inconnues à la fin' })).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath('catalog-filters.png') })
    await page.getByRole('button', { name: 'Effacer les filtres', exact: true }).click()
    await expect(page.locator('.beat-card')).toHaveCount(2)
    await menu('BPM').locator('summary').click()
    await expect(page.getByLabel('BPM minimum')).toHaveValue('')
    await menu('BPM').getByRole('checkbox', { name: 'Non renseigné', exact: true }).check()
    await page.keyboard.press('Escape')
    await expect(page.locator('.beat-card')).toHaveCount(1)
    await expect(page.locator('.beat-card').getByRole('button', { name: 'Écouter Prod beatmaker 2', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Effacer les filtres', exact: true }).click()
    await page.reload()
    await page.getByRole('button', { name: 'Détails de Prod beatmaker 1', exact: true }).click()
    dialog = page.getByRole('dialog')
    await expect(dialog.getByLabel('BPM', { exact: true })).toHaveValue('150')
    await expect(dialog.getByText('Annotations et origine', { exact: true })).toHaveCount(0)
    const persisted = await (await page.request.get(`/api/beats/${seeded.id}`)).json()
    expect(persisted.styles).toEqual(['Hoodtrap'])
    expect([...persisted.moods].sort()).toEqual(['love', 'Mélancolique'].sort())
    await dialog.getByRole('button', { name: 'Modifier la prod', exact: true }).click()
    await dialog.getByLabel('BPM', { exact: true }).fill('')
    await dialog.getByLabel('Tonalité', { exact: true }).fill('')
    await dialog.getByRole('textbox', { name: 'Titre de la prod', exact: true }).fill('Prod annotée')
    await dialog.getByRole('textbox', { name: 'Description de la prod', exact: true }).fill('Description corrigée <script>window.untrusted = true</script>')
    await dialog.getByLabel('Page de vente', { exact: true }).fill('')
    await dialog.getByRole('button', { name: 'Enregistrer les modifications', exact: true }).click()
    await expect(dialog.getByRole('status')).toContainText('Informations enregistrées.')
    await expect(dialog.getByRole('link', { name: 'Page de vente ↗' })).toHaveCount(0)
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await page.reload()
    await page.getByRole('button', { name: 'Détails de Prod annotée', exact: true }).click()
    await expect(page.getByRole('dialog').getByRole('textbox', { name: 'Description de la prod', exact: true })).toHaveValue('Description corrigée <script>window.untrusted = true</script>')
    await expect(page.getByRole('dialog').locator('script')).toHaveCount(0)
  } finally {
    expect((await page.request.post('/api/library', { headers, data: { path: original.root } })).ok()).toBe(true)
    await rm(root, { recursive: true, force: true })
  }
})

test('les filtres restent utilisables sur mobile au clavier et sans débordement', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 650 })
  await page.goto('/')
  const menu = page.locator('.filter-menu').filter({ has: page.locator('summary', { hasText: 'Tonalité' }) })
  await menu.locator('summary').focus()
  await page.keyboard.press('Enter')
  await expect(menu.getByRole('combobox', { name: 'Note', exact: true })).toBeVisible()
  await menu.getByRole('combobox', { name: 'Note', exact: true }).selectOption('F#')
  await menu.getByRole('combobox', { name: 'Mode', exact: true }).selectOption('minor')
  await menu.getByRole('button', { name: 'Ajouter cette tonalité' }).click()
  await menu.getByRole('checkbox', { name: 'F# minor', exact: true }).check()
  await expect(page.getByRole('button', { name: 'Tonalité : F# minor ×', exact: true })).toBeAttached()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('mobile-filters.png') })
  await page.keyboard.press('Escape')
  await expect(menu.locator('.filter-popover')).not.toBeVisible()
})
