const detailsName = 'Détails de R&B Mélancolique'

test('surfaces Paper et 22 textes stables après ouverture en mouvement normal', async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  await page.getByRole('button', { name: detailsName, exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toHaveAttribute('data-state', 'open')
  await expect(dialog).toHaveCSS('backdrop-filter', 'blur(20px)')
  await expect(dialog).toHaveCSS('border-radius', '26px')
  await expect(dialog).toHaveCSS('background-image', 'none')
  await expect(dialog).toHaveCSS('box-shadow', /0px 24px 80px/)
  await expect(dialog.locator('.description-scroll')).toHaveCSS('background-color', 'rgb(34, 42, 54)')
  const session = await page.context().newCDPSession(page)
  const before = await fields(page, session)
  await dialog.getByRole('button', { name: 'Modifier la prod', exact: true }).click()
  expect(await fields(page, session)).toEqual(before)
  await expect(dialog.locator('.description-scroll')).toHaveCSS('background-color', 'rgb(16, 23, 34)')
  await page.screenshot({ path: testInfo.outputPath('detail-paper-surface.png') })
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  for (const name of ['Bibliothèque', 'Diagnostic']) {
    await page.getByRole('button', { name, exact: true }).click()
    const modal = page.getByRole('dialog', { name, exact: true })
    await expect(modal).toHaveAttribute('data-state', 'open')
    await expect(modal).toHaveCSS('background-color', 'rgb(27, 34, 46)')
    await expect(modal).toHaveCSS('backdrop-filter', 'blur(20px)')
    await expect(modal).toHaveCSS('border-radius', '26px')
    const close = modal.getByRole('button', { name: `Fermer la fenêtre ${name}`, exact: true })
    const r = (await close.boundingBox())!
    expect([r.width, r.height]).toEqual([36, 36])
    await page.keyboard.press('Escape')
    await expect(modal).toHaveCount(0)
    await expect(page.getByRole('button', { name, exact: true })).toBeFocused()
  }
  const player = page.getByRole('complementary', { name: 'Lecteur audio' })
  await expect(player).toHaveCSS('backdrop-filter', 'blur(16px)')
  await expect(player).toHaveCSS('box-shadow', /0px 8px 32px/)
  await session.detach()
})

test('fermer pendant l’ouverture repart de la position courante et conserve focus, audio et verrouillage', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  const session = await page.context().newCDPSession(page)
  await session.send('Animation.enable')
  await session.send('Animation.setPlaybackRate', { playbackRate: 0 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Écouter R&B Mélancolique', exact: true }).click()
  const audio = page.locator('audio')
  await expect(audio).toHaveJSProperty('paused', false)
  await audio.evaluate((el: HTMLAudioElement) => { el.pause(); el.currentTime = 7; el.dataset.identity = 'fluid-audio' })
  const trigger = page.getByRole('button', { name: detailsName, exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toHaveAttribute('data-state', 'opening')
  const current = await dialog.evaluate((el) => {
    const animation = el.getAnimations()[0]
    animation.pause(); animation.currentTime = 60
    const style = getComputedStyle(el)
    return { opacity: Number(style.opacity), y: new DOMMatrix(style.transform).m42, duration: animation.effect!.getTiming().duration }
  })
  expect(current.duration).toBe(180)
  expect(current.opacity).toBeGreaterThan(0); expect(current.opacity).toBeLessThan(1)
  expect(current.y).toBeGreaterThan(0); expect(current.y).toBeLessThan(8)
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveAttribute('data-state', 'closing')
  const closing = await dialog.evaluate((el) => {
    const animation = el.getAnimations()[0]
    const frames = (animation.effect as KeyframeEffect).getKeyframes()
    return { opacity: Number(frames[0].opacity), y: new DOMMatrix(String(frames[0].transform)).m42, duration: animation.effect!.getTiming().duration }
  })
  expect(closing.duration).toBe(140)
  expect(closing.opacity).toBeCloseTo(current.opacity, 4)
  expect(closing.y).toBeCloseTo(current.y, 4)
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('hidden')
  expect(await dialog.evaluate((el) => el.contains(document.activeElement))).toBe(true)
  await page.keyboard.press('Escape')
  await dialog.evaluate((el) => el.getAnimations()[0].finish())
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('')
  await expect(audio).toHaveAttribute('data-identity', 'fluid-audio')
  await expect(audio).toHaveJSProperty('paused', true)
  await expect(audio).toHaveJSProperty('currentTime', 7)
  await session.send('Animation.setPlaybackRate', { playbackRate: 1 })
  await session.detach()
})

