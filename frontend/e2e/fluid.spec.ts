for (const layout of ['Grandes pochettes', 'Cartes horizontales']) {
  test(`pression de l’icône seule et six états sans déplacement : ${layout}`, async ({ page }, testInfo) => {
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await page.goto('/')
    await page.getByRole('button', { name: layout, exact: true }).click()
    const card = page.locator('.beat-card').filter({ has: page.getByRole('button', { name: detailsName, exact: true }) })
    await expect(card).not.toHaveClass(/selected/)
    const cover = card.locator('.beat-select, .horizontal-cover')
    const info = card.getByRole('button', { name: detailsName, exact: true })
    const audio = page.locator('audio')
    const boxes = () => card.locator(':scope, .beat-select, .horizontal-cover, .beat-card-info, .horizontal-details, .beat-favorite').evaluateAll((els) => els.map((el) => { const r = el.getBoundingClientRect(); return [r.x, r.y, r.width, r.height] }))
    const before = await boxes()
    await cover.hover()
    await expect(card.locator('.cover-play')).toHaveCSS('opacity', '1')
    expect(await boxes()).toEqual(before)
    await page.mouse.down()
    await expect(card.locator('.cover-play svg')).toHaveCSS('transform', 'matrix(0.96, 0, 0, 0.96, 0, 0)')
    await expect(audio).toHaveJSProperty('paused', true)
    expect(await boxes()).toEqual(before)
    await page.mouse.up()
    await expect(audio).toHaveJSProperty('paused', false)
    await page.mouse.move(0, 0)
    await expect(card.locator('.cover-play svg')).toHaveAttribute('data-icon', 'pause')
    await expect(card.locator('.cover-play')).toHaveCSS('opacity', '1')
    expect(await boxes()).toEqual(before)
    await audio.evaluate((el: HTMLAudioElement) => el.pause())
    await expect(card).toHaveClass(/selected/)
    await expect(card).not.toHaveClass(/is-playing/)
    await expect(card.locator('.cover-play svg')).toHaveAttribute('data-icon', 'play')
    await info.hover(); await cover.focus(); await page.keyboard.press('Tab')
    await expect(info).toBeFocused()
    await expect(info).toHaveCSS('outline-style', 'solid')
    expect(await boxes()).toEqual(before)
    await page.screenshot({ path: testInfo.outputPath('card-states.png') })
    await audio.evaluate((el: HTMLAudioElement) => el.dispatchEvent(new Event('error')))
    await expect(card.locator('.cover-play svg')).toHaveAttribute('data-icon', 'play')
  })
}

test('mouvement réduit sans translation et surfaces opaques avec transparence réduite', async ({ page }) => {
  const session = await page.context().newCDPSession(page)
  await session.send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }, { name: 'prefers-reduced-transparency', value: 'reduce' }] })
  await session.send('Animation.enable')
  await session.send('Animation.setPlaybackRate', { playbackRate: 0 })
  await page.goto('/')
  await page.getByRole('button', { name: detailsName, exact: true }).click()
  const dialog = page.getByRole('dialog')
  const animation = await dialog.evaluate((el) => {
    const a = el.getAnimations()[0]
    return { duration: a.effect!.getTiming().duration, transforms: (a.effect as KeyframeEffect).getKeyframes().map((frame) => frame.transform) }
  })
  expect(animation.duration).toBe(80)
  expect(animation.transforms).toEqual(['none', 'none'])
  await expect(dialog).toHaveCSS('backdrop-filter', 'none')
  await expect(dialog).toHaveCSS('background-color', 'rgb(27, 34, 46)')
  await expect(page.locator('.local-player')).toHaveCSS('background-color', 'rgb(30, 39, 45)')
  await dialog.evaluate((el) => el.getAnimations()[0].finish())
  await page.keyboard.press('Escape')
  await dialog.evaluate((el) => el.getAnimations()[0].finish())
  await expect(dialog).toHaveCount(0)
  await session.send('Animation.setPlaybackRate', { playbackRate: 1 })
  await session.detach()
})
